def is_holiday(country: str, day: datetime.date) -> bool:
    return day.isoformat() in HOLIDAYS_2026.get(country, [])


def is_business_day(country: str, day: datetime.date) -> bool:
    return day.weekday() < 5 and not is_holiday(country, day)


def next_business_day(country: str, day: datetime.date) -> datetime.date:
    """The first business day strictly after ``day``."""
    candidate = day + datetime.timedelta(days=1)
    while not is_business_day(country, candidate):
        candidate += datetime.timedelta(days=1)
    return candidate
